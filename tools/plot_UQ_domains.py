# Status codes matching gridgen and UGRID conventions:
# 0 = Land (dry) -> dark green
# 1 = Sea / wet (active calculation points) -> partition colors
# 2 = Boundary points -> magenta
# 3 = Excluded points -> light gray
VAL_EXCLUDED = -3
VAL_BOUNDARY = -2
VAL_LAND = -1

# Distinct qualitative colors for partition assignments (avoiding dark green, magenta, and light gray reserved for features)
DISTINCT_PARTITION_PALETTE = [
    "#1f77b4",  # blue
    "#ff7f0e",  # orange
    "#9467bd",  # purple
    "#d62728",  # red
    "#8c564b",  # brown
    "#17becf",  # cyan
    "#bcbd22",  # olive-yellow
    "#aec7e8",  # light blue
    "#ffbb78",  # light orange
    "#c5b0d5",  # light purple
    "#ff9896",  # light red
    "#ffd92f",  # gold
]


def find_associated_grid_file(part_filepath: Path) -> Path | None:
    """
    Search for an associated UGRID grid file in the same directory as the partition file.
    E.g., for `grid.partitions.nc`, looks for `grid.nc`.
    """
    name = part_filepath.name
    parent = part_filepath.parent

    candidates: list[Path] = []
    if ".partitions." in name:
        candidates.append(parent / name.replace(".partitions.", "."))
    if name.endswith(".partitions"):
        candidates.append(parent / name[:-11])
    if name.endswith(".partitions.nc"):
        candidates.append(parent / (name[:-14] + ".nc"))

    for cand in candidates:
        if cand.exists():
            return cand
    return None


def read_grid_mask(grid_filepath: Path) -> np.ndarray | None:
    """
    Read the 2D grid_mask array from an associated UGRID grid file.
    """
    try:
        with nc.Dataset(str(grid_filepath), "r") as ds:
            if "grid_mask" in ds.variables:
                return np.array(ds.variables["grid_mask"][:], dtype=np.int32)
            if "mask" in ds.variables:
                mask_var = np.array(ds.variables["mask"][:], dtype=np.int32)
                ny = getattr(ds, "ny", None) or ds.dimensions.get("ny", None)
                nx = getattr(ds, "nx", None) or ds.dimensions.get("nx", None)
                if ny is not None and nx is not None:
                    ny_len = ny.size if hasattr(ny, "size") else int(ny)
                    nx_len = nx.size if hasattr(nx, "size") else int(nx)
                    if mask_var.size == ny_len * nx_len:
                        return mask_var.reshape((ny_len, nx_len))
    except (OSError, KeyError, ValueError) as err:
        print(f"Notice: Could not load mask from associated grid file: {err}")
    return None


def read_partition_file(filepath: Path):
    """
    Read partition map dataset and metadata from a NetCDF partition file.

    Parameters
    ----------
    filepath : Path
        Path to the NetCDF partition file.

    Returns
    -------
    tuple
        (maps, num_partitions, grid_title, grid_mask)
        maps: np.ndarray with shape (n_maps, ny, nx)
        num_partitions: int
        grid_title: str
        grid_mask: np.ndarray | None
    """
    if not filepath.exists():
        raise FileNotFoundError(f"Partition file not found: {filepath}")

    with nc.Dataset(str(filepath), "r") as ds:
        num_partitions = getattr(ds, "num_partitions", 0)
        grid_title = getattr(ds, "title", filepath.name)

        if "partition_map" not in ds.variables:
            raise KeyError("Variable 'partition_map' not found in NetCDF file.")

        var = ds.variables["partition_map"]
        maps = np.array(var[:], dtype=np.int32)

        if maps.ndim == 2:
            maps = maps[np.newaxis, :, :]

        # Look for grid_mask or mask inside the partition file itself if stored
        grid_mask = None
        if "grid_mask" in ds.variables:
            grid_mask = np.array(ds.variables["grid_mask"][:], dtype=np.int32)
        elif "mask" in ds.variables:
            mask_data = np.array(ds.variables["mask"][:], dtype=np.int32)
            if mask_data.ndim == 2:
                grid_mask = mask_data
            elif mask_data.size == maps.shape[1] * maps.shape[2]:
                grid_mask = mask_data.reshape((maps.shape[1], maps.shape[2]))

    # If grid_mask was not found directly in partition file, look for an associated grid file
    if grid_mask is None:
        assoc_grid = find_associated_grid_file(filepath)
        if assoc_grid is not None:
            grid_mask = read_grid_mask(assoc_grid)

    return maps, num_partitions, grid_title, grid_mask


def build_partition_adjacency_graph(maps: np.ndarray) -> dict[int, set[int]]:
    """
    Build an adjacency graph of partition IDs across maps using 4-connectivity.
    """
    adj: dict[int, set[int]] = {}
    pids = sorted([int(p) for p in np.unique(maps) if p > 0])
    for p in pids:
        adj[p] = set()

    for m in range(maps.shape[0]):
        slice_data = maps[m]

        # Horizontal neighbors
        diff_h = slice_data[:, :-1] != slice_data[:, 1:]
        p1_h = slice_data[:, :-1][diff_h]
        p2_h = slice_data[:, 1:][diff_h]
        for u, v in zip(p1_h, p2_h):
            if u > 0 and v > 0 and u != v:
                adj[int(u)].add(int(v))
                adj[int(v)].add(int(u))

        # Vertical neighbors
        diff_v = slice_data[:-1, :] != slice_data[1:, :]
        p1_v = slice_data[:-1, :][diff_v]
        p2_v = slice_data[1:, :][diff_v]
        for u, v in zip(p1_v, p2_v):
            if u > 0 and v > 0 and u != v:
                adj[int(u)].add(int(v))
                adj[int(v)].add(int(u))

    return adj


def compute_minimal_partition_coloring(
    adj: dict[int, set[int]],
) -> dict[int, int]:
    """
    Compute minimal chromatic graph coloring using the DSATUR / Welsh-Powell heuristic
    such that adjacent partitions never have the same color.
    """
    if not adj:
        return {}

    # Sort partitions by degree descending
    ordered_nodes = sorted(adj.keys(), key=lambda node: len(adj[node]), reverse=True)
    color_map: dict[int, int] = {}

    for node in ordered_nodes:
        neighbor_colors = {
            color_map[neighbor] for neighbor in adj[node] if neighbor in color_map
        }
        color_idx = 0
        while color_idx in neighbor_colors:
            color_idx += 1
        color_map[node] = color_idx

    return color_map


def build_display_array(
    partition_slice: np.ndarray,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None,
) -> tuple[np.ndarray, bool, bool]:
    """
    Combine partition slice and land/sea/boundary/excluded mask into a single
    display index array:
      -3: Excluded points
      -2: Boundary points
      -1: Land points
      0..num_colors-1: Partition colors
    """
    ny, nx = partition_slice.shape
    disp = np.full((ny, nx), VAL_LAND, dtype=np.int32)

    has_boundary = False
    has_excluded = False

    # First apply grid mask features if available
    if grid_mask is not None and grid_mask.shape == (ny, nx):
        disp[grid_mask == 0] = VAL_LAND
        if np.any(grid_mask == 2):
            disp[grid_mask == 2] = VAL_BOUNDARY
            has_boundary = True
        if np.any(grid_mask == 3):
            disp[grid_mask == 3] = VAL_EXCLUDED
            has_excluded = True

    # Then overlay partition IDs
    for p, c_idx in color_map.items():
        disp[partition_slice == p] = c_idx

    return disp, has_boundary, has_excluded


def get_feature_colormap(num_partition_colors: int):
    """
    Create colormap and normalization for:
      -3: Excluded points (light gray #d0d0d0)
      -2: Boundary points (magenta #ff00ff)
      -1: Land points (dark green #006400)
      0..num_partition_colors-1: Distinct partition colors
    """
    num_partition_colors = max(num_partition_colors, 1)

    c_excluded = "#d0d0d0"  # light gray
    c_boundary = "#ff00ff"  # magenta
    c_land = "#006400"  # dark green

    color_list = [c_excluded, c_boundary, c_land]
    for i in range(num_partition_colors):
        color_list.append(
            DISTINCT_PARTITION_PALETTE[i % len(DISTINCT_PARTITION_PALETTE)]
        )

    cmap = colors.ListedColormap(color_list)
    bounds = np.arange(-3.5, num_partition_colors + 0.5, 1.0)
    norm = colors.BoundaryNorm(bounds, cmap.N)
    return cmap, norm


def setup_plot_axes(
    ax: plt.Axes,
    disp_data: np.ndarray,
    cmap: colors.Colormap,
    norm: colors.Normalize,
    title: str,
    color_map: dict[int, int],
    has_boundary: bool,
    has_excluded: bool,
):
    """
    Render map slice on Cartesian grid using box-fill representation (pcolormesh)
    with equal aspect ratio and cleanly placed feature legend.
    """
    ny, nx = disp_data.shape
    ax.set_aspect("equal", adjustable="box")

    # Box-fill rendering: pcolormesh accurately draws pixel grid boxes on Cartesian coordinates
    x_edges = np.arange(nx + 1)
    y_edges = np.arange(ny + 1)
    ax.pcolormesh(
        x_edges,
        y_edges,
        disp_data,
        cmap=cmap,
        norm=norm,
        edgecolors="none",
        shading="flat",
    )

    ax.set_xlim(0, nx)
    ax.set_ylim(0, ny)
    ax.set_xlabel("X (Grid columns)")
    ax.set_ylabel("Y (Grid rows)")
    ax.set_title(title, fontsize=11, fontweight="bold")

    # Legend elements:
    # Feature markers conforming to gridgen development branch
    legend_patches = [
        mpatches.Patch(
            facecolor="#006400", edgecolor="black", linewidth=0.5, label="Land"
        )
    ]
    if has_boundary:
        legend_patches.append(
            mpatches.Patch(
                facecolor="#ff00ff",
                edgecolor="black",
                linewidth=0.5,
                label="Boundary",
            )
        )
    if has_excluded:
        legend_patches.append(
            mpatches.Patch(
                facecolor="#d0d0d0",
                edgecolor="black",
                linewidth=0.5,
                label="Excluded",
            )
        )

    # Partition color swatches
    num_p_colors = max(color_map.values()) + 1 if color_map else 1
    for c in range(num_p_colors):
        p_list = [p for p, col in color_map.items() if col == c]
        if len(p_list) <= 6:
            lbl = f"Part: {', '.join(map(str, sorted(p_list)))}"
        else:
            lbl = f"Part ({len(p_list)} domains)"
        color_val = DISTINCT_PARTITION_PALETTE[c % len(DISTINCT_PARTITION_PALETTE)]
        legend_patches.append(
            mpatches.Patch(
                facecolor=color_val,
                edgecolor="black",
                linewidth=0.5,
                label=lbl,
            )
        )

    ax.legend(
        handles=legend_patches,
        loc="upper left",
        bbox_to_anchor=(1.02, 1.0),
        borderaxespad=0.0,
        fontsize=9,
        frameon=True,
    )


def sample_indices(total_maps: int, step: int) -> list[int]:
    """
    Select map indices according to step/stride, always ensuring the first (0)
    and last (total_maps - 1) iterations are included.
    """
    if total_maps <= 1:
        return [0]

    step = max(1, step)
    selected = list(range(0, total_maps, step))
    if (total_maps - 1) not in selected:
        selected.append(total_maps - 1)
    return sorted(set(selected))


def plot_single_map(
    map_data: np.ndarray,
    map_idx: int,
    total_maps: int,
    num_partitions: int,
    title_prefix: str,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None,
    output_path: Path | None = None,
):
    """
    Plot the full partition map array on a Cartesian grid with equal aspect ratio.
    """
    disp, has_boundary, has_excluded = build_display_array(
        map_data, color_map, grid_mask
    )
    num_p_colors = max(color_map.values()) + 1 if color_map else 1
    cmap, norm = get_feature_colormap(num_p_colors)

    fig, ax = plt.subplots(figsize=(9, 6))

    step_str = f" [Step {map_idx + 1}/{total_maps}]" if total_maps > 1 else ""
    title = (
        f"{title_prefix}{step_str}\n"
        f"Partitions: {num_partitions} (Colors used: {num_p_colors})"
    )

    setup_plot_axes(
        ax,
        disp,
        cmap,
        norm,
        title,
        color_map,
        has_boundary,
        has_excluded,
    )

    plt.tight_layout()

    if output_path is not None:
        plt.savefig(str(output_path), dpi=150, bbox_inches="tight")
        plt.close(fig)
        print(f"Saved plot to: {output_path}")
    else:
        plt.show()


def create_animation(
    maps: np.ndarray,
    indices: list[int],
    num_partitions: int,
    title_prefix: str,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None,
    output_path: Path,
    fps: int = 2,
):
    """
    Generate an animated GIF across sampled map iterations.
    """
    try:
        import imageio.v3 as iio
    except ImportError:
        try:
            import imageio as iio
        except ImportError:
            raise ImportError(
                "imageio library is required for animated GIF generation."
            )

    import io

    from PIL import Image

    total_maps = maps.shape[0]
    num_p_colors = max(color_map.values()) + 1 if color_map else 1
    cmap, norm = get_feature_colormap(num_p_colors)

    frames = []
    for idx in indices:
        disp, has_boundary, has_excluded = build_display_array(
            maps[idx], color_map, grid_mask
        )

        fig, ax = plt.subplots(figsize=(9, 6))
        title = (
            f"{title_prefix} [Step {idx + 1}/{total_maps}]\n"
            f"Partitions: {num_partitions} (Colors used: {num_p_colors})"
        )

        setup_plot_axes(
            ax,
            disp,
            cmap,
            norm,
            title,
            color_map,
            has_boundary,
            has_excluded,
        )

        plt.tight_layout()

        buf = io.BytesIO()
        plt.savefig(buf, format="png", dpi=120, bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        frames.append(np.array(Image.open(buf)))

    duration_ms = int(1000.0 / max(1, fps))
    iio.imwrite(
        str(output_path),
        frames,
        duration=duration_ms,
        loop=0,
    )
    print(
        f"Saved animation ({len(frames)} frames from {total_maps} total maps) to: {output_path}"
    )


def main():
    """
    Main entry point for plot_UQ_domains.
    """
    parser = argparse.ArgumentParser(
        description="Plot WAVEWATCH IV UQ grid partition maps from NetCDF file."
    )
    parser.add_argument(
        "partition_file",
        type=str,
        help="Path to the NetCDF partition file (mandatory first input).",
    )
    parser.add_argument(
        "--type",
        "-t",
        type=str,
        default="png",
        help="Output graphic format (e.g. png, jpg, jpeg, pdf, eps, gif). Default: png.",
    )
    parser.add_argument(
        "--animate",
        action="store_true",
        help="Generate animated GIF across map iterations.",
    )
    parser.add_argument(
        "--step",
        "-n",
        type=int,
        default=1,
        help="Sample every n-th iteration / map in animations (default: 1). Initial and final maps are always included.",
    )
    parser.add_argument(
        "--fps",
        type=int,
        default=2,
        help="Frames per second for animation (default: 2).",
    )

    args = parser.parse_args()
    input_path = Path(args.partition_file)

    try:
        maps, num_partitions, grid_title, grid_mask = read_partition_file(input_path)
    except (OSError, KeyError, ValueError) as e:
        print(f"Error reading partition file: {e}")
        sys.exit(1)

    total_maps = maps.shape[0]
    if num_partitions <= 0:
        num_partitions = int(np.max(maps))

    # Clean and determine output file extension
    out_ext = args.type.strip().lower().lstrip(".")
    if not out_ext:
        out_ext = "png"

    # Derive output filename from input file name, replacing .nc with graphic extension
    input_filename = input_path.name
    if input_filename.endswith(".nc"):
        base_name = input_filename[:-3]
    else:
        base_name = input_path.stem
    output_filename = f"{base_name}.{out_ext}"

    # Always produce output in the current working directory where the tool is executed
    output_path = Path.cwd() / output_filename

    # Build adjacency graph and minimal graph coloring across all partitions
    adj = build_partition_adjacency_graph(maps)
    color_map = compute_minimal_partition_coloring(adj)

    # Animate if requested or if output format is gif
    is_gif = out_ext == "gif"
    if args.animate or is_gif:
        if total_maps < 2:
            print(
                "Notice: File contains only 1 partition map. Generating single image/gif frame."
            )
        if not output_filename.endswith(".gif"):
            output_path = Path.cwd() / f"{base_name}.gif"

        indices = sample_indices(total_maps, args.step)
        create_animation(
            maps,
            indices,
            num_partitions,
            grid_title,
            color_map,
            grid_mask,
            output_path,
            fps=args.fps,
        )
    else:
        # Plot the entire map array for the final map iteration
        last_idx = total_maps - 1
        plot_single_map(
            maps[last_idx],
            last_idx,
            total_maps,
            num_partitions,
            grid_title,
            color_map,
            grid_mask,
            output_path,
        )


if __name__ == "__main__":
    main()
