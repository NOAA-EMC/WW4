import argparse
import sys
from pathlib import Path

try:
    import matplotlib.pyplot as plt
    import netCDF4 as nc
    import numpy as np
    from matplotlib import colors
except ImportError as err:
    print(
        f"Error: Missing required Python dependencies ({err}). Please install netCDF4, matplotlib, numpy."
    )
    sys.exit(1)


def read_partition_file(filepath: Path):
    """
    Read partition map dataset and metadata from a NetCDF partition file.

    Parameters
    ----------
    filepath : Path
        Path to the NetCDF partition file.

    Returns
    -------
    tuple
        (maps, num_partitions, grid_title)
        maps: np.ndarray with shape (n_maps, ny, nx) or (ny, nx)
        num_partitions: int
        grid_title: str
    """
    if not filepath.exists():
        raise FileNotFoundError(f"Partition file not found: {filepath}")

    with nc.Dataset(str(filepath), "r") as ds:
        num_partitions = getattr(ds, "num_partitions", 0)
        grid_title = getattr(ds, "title", filepath.name)

        if "partition_map" not in ds.variables:
            raise KeyError("Variable 'partition_map' not found in NetCDF file.")

        var = ds.variables["partition_map"]
        data = np.array(var[:])

        if data.ndim == 2:
            data = data[np.newaxis, :, :]

    return data, num_partitions, grid_title


def build_discrete_cmap(num_partitions: int):
    """
    Build a discrete colormap and boundary norm where 0 is land (light gray)
    and 1..num_partitions are distinct colors.
    """
    num_partitions = max(num_partitions, 1)

    # Base qualitative colormap
    base_cmap = plt.get_cmap("tab20" if num_partitions <= 20 else "gist_ncar")
    color_list = ["#d0d0d0"]  # index 0 is land

    for i in range(1, num_partitions + 1):
        color_list.append(base_cmap((i - 1) % base_cmap.N))

    cmap = colors.ListedColormap(color_list)
    bounds = np.arange(-0.5, num_partitions + 1.5, 1.0)
    norm = colors.BoundaryNorm(bounds, cmap.N)
    return cmap, norm


def plot_single_map(
    map_data: np.ndarray,
    map_idx: int,
    total_maps: int,
    num_partitions: int,
    title_prefix: str,
    output_path: Path | None = None,
):
    """
    Plot a single partition map slice on a Cartesian grid with equal aspect ratio.
    """
    ny, nx = map_data.shape
    cmap, norm = build_discrete_cmap(num_partitions)

    fig, ax = plt.subplots(figsize=(8, 6))

    # Equal aspect ratio for square/Cartesian grid
    ax.set_aspect("equal", adjustable="box")

    im = ax.imshow(
        map_data,
        cmap=cmap,
        norm=norm,
        origin="lower",
        extent=(0, nx, 0, ny),
        interpolation="nearest",
    )

    ax.set_xlabel("X (Grid columns)")
    ax.set_ylabel("Y (Grid rows)")
    step_str = f" [Step {map_idx + 1}/{total_maps}]" if total_maps > 1 else ""
    ax.set_title(f"{title_prefix}{step_str}\nPartitions: {num_partitions}")

    cbar = fig.colorbar(
        im,
        ax=ax,
        ticks=np.arange(0, num_partitions + 1),
        fraction=0.046,
        pad=0.04,
    )
    cbar.set_label("Partition ID (0 = Land)")

    plt.tight_layout()

    if output_path is not None:
        plt.savefig(str(output_path), dpi=150)
        plt.close(fig)
        print(f"Saved plot to: {output_path}")
    else:
        plt.show()


def create_animation(
    maps: np.ndarray,
    num_partitions: int,
    title_prefix: str,
    output_path: Path,
    fps: int = 2,
):
    """
    Generate an animated GIF showing the evolution across all maps.
    """
    try:
        import imageio.v3 as iio
    except ImportError:
        try:
            import imageio as iio
        except ImportError:
            raise ImportError(
                "imageio library is required for animated GIF generation."
            )

    import io

    from PIL import Image

    total_maps = maps.shape[0]
    frames = []

    ny, nx = maps.shape[1], maps.shape[2]
    cmap, norm = build_discrete_cmap(num_partitions)

    for idx in range(total_maps):
        fig, ax = plt.subplots(figsize=(8, 6))
        ax.set_aspect("equal", adjustable="box")

        im = ax.imshow(
            maps[idx],
            cmap=cmap,
            norm=norm,
            origin="lower",
            extent=(0, nx, 0, ny),
            interpolation="nearest",
        )

        ax.set_xlabel("X (Grid columns)")
        ax.set_ylabel("Y (Grid rows)")
        ax.set_title(
            f"{title_prefix} [Step {idx + 1}/{total_maps}]\nPartitions: {num_partitions}"
        )

        cbar = fig.colorbar(
            im,
            ax=ax,
            ticks=np.arange(0, num_partitions + 1),
            fraction=0.046,
            pad=0.04,
        )
        cbar.set_label("Partition ID (0 = Land)")
        plt.tight_layout()

        buf = io.BytesIO()
        plt.savefig(buf, format="png", dpi=120)
        plt.close(fig)
        buf.seek(0)
        frames.append(np.array(Image.open(buf)))

    duration_ms = int(1000.0 / max(1, fps))
    iio.imwrite(
        str(output_path),
        frames,
        duration=duration_ms,
        loop=0,
    )
    print(f"Saved animation ({total_maps} frames) to: {output_path}")


def main():
    """
    Main entry point for plot_UQ_domains.
    """
    parser = argparse.ArgumentParser(
        description="Plot WAVEWATCH IV UQ grid partition maps from NetCDF file."
    )
    parser.add_argument(
        "--input",
        "-i",
        type=str,
        required=True,
        help="Path to the NetCDF partition file.",
    )
    parser.add_argument(
        "--type",
        "-t",
        type=str,
        default="png",
        help="Output graphic format (e.g. png, jpg, jpeg, pdf, eps, gif). Default: png.",
    )
    parser.add_argument(
        "--index",
        type=int,
        default=-1,
        help="Map index to display (0-based, default: -1 for last map).",
    )
    parser.add_argument(
        "--animate",
        action="store_true",
        help="Generate animated GIF across all maps in the partition file.",
    )
    parser.add_argument(
        "--fps",
        type=int,
        default=2,
        help="Frames per second for animation (default: 2).",
    )

    args = parser.parse_args()
    input_path = Path(args.input)

    try:
        maps, num_partitions, grid_title = read_partition_file(input_path)
    except (OSError, KeyError, ValueError) as e:
        print(f"Error reading partition file: {e}")
        sys.exit(1)

    total_maps = maps.shape[0]
    if num_partitions <= 0:
        num_partitions = int(np.max(maps))

    # Clean and determine output file extension
    out_ext = args.type.strip().lower().lstrip(".")
    if not out_ext:
        out_ext = "png"

    # Derive output filename from input file name, replacing .nc with graphic extension
    input_filename = input_path.name
    if input_filename.endswith(".nc"):
        base_name = input_filename[:-3]
    else:
        base_name = input_path.stem
    output_filename = f"{base_name}.{out_ext}"

    # Always produce output in the current working directory where the tool is executed
    output_path = Path.cwd() / output_filename

    # Animate if requested or if output format is gif
    is_gif = out_ext == "gif"
    if args.animate or is_gif:
        if total_maps < 2:
            print(
                "Notice: File contains only 1 partition map. Generating single image/gif frame."
            )
        if not output_filename.endswith(".gif"):
            output_path = Path.cwd() / f"{base_name}.gif"

        create_animation(
            maps,
            num_partitions,
            grid_title,
            output_path,
            fps=args.fps,
        )
    else:
        # Resolve map index
        idx = args.index
        if idx < 0:
            idx = total_maps + idx
        if idx < 0 or idx >= total_maps:
            print(f"Error: Map index {args.index} out of range [0, {total_maps - 1}].")
            sys.exit(1)

        plot_single_map(
            maps[idx],
            idx,
            total_maps,
            num_partitions,
            grid_title,
            output_path,
        )


if __name__ == "__main__":
    main()
