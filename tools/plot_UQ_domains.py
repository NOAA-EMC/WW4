# Status codes matching gridgen and UGRID conventions:
# 0 = Land (dry) -> dark green
# 1 = Sea / wet (active calculation points) -> domain colors
# 2 = Boundary points -> magenta
# 3 = Excluded points -> light gray
VAL_EXCLUDED = -3
VAL_BOUNDARY = -2
VAL_LAND = -1

# Distinct qualitative colors for domain assignments (up to 10 colors, avoiding dark green, magenta, and light gray reserved for features)
DISTINCT_DOMAIN_PALETTE = [
    "#1f77b4",  # blue
    "#ff7f0e",  # orange
    "#9467bd",  # purple
    "#d62728",  # red
    "#8c564b",  # brown
    "#17becf",  # cyan
    "#bcbd22",  # olive-yellow
    "#aec7e8",  # light blue
    "#ffbb78",  # light orange
    "#ffd92f",  # gold
]


def find_associated_grid_file(domain_filepath: Path) -> Path | None:
    """
    Search for an associated UGRID grid file in the same directory as the domain file.
    E.g., for `grid.partitions.nc` or `grid.domains.nc`, looks for `grid.nc`.
    """
    name = domain_filepath.name
    parent = domain_filepath.parent

    candidates: list[Path] = []
    if ".partitions." in name:
        candidates.append(parent / name.replace(".partitions.", "."))
    if name.endswith(".partitions"):
        candidates.append(parent / name[:-11])
    if name.endswith(".partitions.nc"):
        candidates.append(parent / (name[:-14] + ".nc"))
    if ".domains." in name:
        candidates.append(parent / name.replace(".domains.", "."))
    if name.endswith(".domains"):
        candidates.append(parent / name[:-8])
    if name.endswith(".domains.nc"):
        candidates.append(parent / (name[:-11] + ".nc"))

    for cand in candidates:
        if cand.exists():
            return cand
    return None


def read_grid_mask(grid_filepath: Path) -> np.ndarray | None:
    """
    Read the 2D grid_mask array from an associated UGRID grid file.
    """
    try:
        with nc.Dataset(str(grid_filepath), "r") as ds:
            if "grid_mask" in ds.variables:
                return np.array(ds.variables["grid_mask"][:], dtype=np.int32)
            if "mask" in ds.variables:
                mask_var = np.array(ds.variables["mask"][:], dtype=np.int32)
                ny = getattr(ds, "ny", None) or ds.dimensions.get("ny", None)
                nx = getattr(ds, "nx", None) or ds.dimensions.get("nx", None)
                if ny is not None and nx is not None:
                    ny_len = ny.size if hasattr(ny, "size") else int(ny)
                    nx_len = nx.size if hasattr(nx, "size") else int(nx)
                    if mask_var.size == ny_len * nx_len:
                        return mask_var.reshape((ny_len, nx_len))
    except (OSError, KeyError, ValueError) as err:
        print(f"Notice: Could not load mask from associated grid file: {err}")
    return None


def read_domain_file(filepath: Path):
    """
    Read domain map dataset and metadata from a NetCDF domain file.

    Parameters
    ----------
    filepath : Path
        Path to the NetCDF domain file.

    Returns
    -------
    tuple
        (maps, num_domains, grid_title, grid_mask, is_global)
        maps: np.ndarray with shape (n_maps, ny, nx)
        num_domains: int
        grid_title: str
        grid_mask: np.ndarray | None
        is_global: bool
    """
    if not filepath.exists():
        raise FileNotFoundError(f"Domain file not found: {filepath}")

    with nc.Dataset(str(filepath), "r") as ds:
        num_domains = getattr(ds, "num_domains", None)
        if num_domains is None:
            num_domains = getattr(ds, "num_partitions", 0)
        grid_title = getattr(ds, "title", filepath.name)
        closure_att = str(getattr(ds, "global_closure", "")).lower()
        is_global = closure_att in ["closed", "true", "yes", "1"]

        var = None
        if "domain_map" in ds.variables:
            var = ds.variables["domain_map"]
        elif "partition_map" in ds.variables:
            var = ds.variables["partition_map"]
        else:
            raise KeyError(
                "Variable 'domain_map' or 'partition_map' not found in NetCDF file."
            )

        maps = np.array(var[:], dtype=np.int32)

        if maps.ndim == 2:
            maps = maps[np.newaxis, :, :]

        # Look for grid_mask or mask inside the domain file itself if stored
        grid_mask = None
        if "grid_mask" in ds.variables:
            grid_mask = np.array(ds.variables["grid_mask"][:], dtype=np.int32)
        elif "mask" in ds.variables:
            mask_data = np.array(ds.variables["mask"][:], dtype=np.int32)
            if mask_data.ndim == 2:
                grid_mask = mask_data
            elif mask_data.size == maps.shape[1] * maps.shape[2]:
                grid_mask = mask_data.reshape((maps.shape[1], maps.shape[2]))

    # If grid_mask was not found directly in domain file, look for an associated grid file
    if grid_mask is None:
        assoc_grid = find_associated_grid_file(filepath)
        if assoc_grid is not None:
            grid_mask = read_grid_mask(assoc_grid)
            if not is_global:
                try:
                    with nc.Dataset(str(assoc_grid), "r") as ds_g:
                        closure_g = str(getattr(ds_g, "global_closure", "")).lower()
                        if closure_g in ["closed", "true", "yes", "1"]:
                            is_global = True
                except (OSError, KeyError, ValueError):
                    pass

    return maps, num_domains, grid_title, grid_mask, is_global


def build_domain_adjacency_graph(
    maps: np.ndarray, is_global: bool = False
) -> dict[int, set[int]]:
    """
    Build an adjacency graph of domain IDs across maps using 4-connectivity.
    """
    adj: dict[int, set[int]] = {}
    pids = sorted([int(p) for p in np.unique(maps) if p > 0])
    for p in pids:
        adj[p] = set()

    for m in range(maps.shape[0]):
        slice_data = maps[m]

        # Horizontal neighbors
        diff_h = slice_data[:, :-1] != slice_data[:, 1:]
        p1_h = slice_data[:, :-1][diff_h]
        p2_h = slice_data[:, 1:][diff_h]
        for u, v in zip(p1_h, p2_h):
            if u > 0 and v > 0 and u != v:
                adj[int(u)].add(int(v))
                adj[int(v)].add(int(u))

        # Check global closure boundary (between last and first column)
        if is_global and slice_data.shape[1] > 1:
            diff_wrap = slice_data[:, -1] != slice_data[:, 0]
            p1_w = slice_data[:, -1][diff_wrap]
            p2_w = slice_data[:, 0][diff_wrap]
            for u, v in zip(p1_w, p2_w):
                if u > 0 and v > 0 and u != v:
                    adj[int(u)].add(int(v))
                    adj[int(v)].add(int(u))

        # Vertical neighbors
        diff_v = slice_data[:-1, :] != slice_data[1:, :]
        p1_v = slice_data[:-1, :][diff_v]
        p2_v = slice_data[1:, :][diff_v]
        for u, v in zip(p1_v, p2_v):
            if u > 0 and v > 0 and u != v:
                adj[int(u)].add(int(v))
                adj[int(v)].add(int(u))

    return adj


def compute_minimal_domain_coloring(
    adj: dict[int, set[int]],
    max_colors: int = 10,
) -> dict[int, int]:
    """
    Compute minimal chromatic graph coloring using the DSATUR / Welsh-Powell heuristic
    such that adjacent domains never have the same color, using at most max_colors.
    """
    if not adj:
        return {}

    # Sort domains by degree descending
    ordered_nodes = sorted(adj.keys(), key=lambda node: len(adj[node]), reverse=True)
    color_map: dict[int, int] = {}

    for node in ordered_nodes:
        neighbor_colors = {
            color_map[neighbor] for neighbor in adj[node] if neighbor in color_map
        }
        color_idx = 0
        while color_idx in neighbor_colors:
            color_idx += 1
            if color_idx >= max_colors:
                # If all colors up to max_colors are taken by neighbors, fall back to
                # least-frequently used color among non-conflicting or modulo wrap
                break
        color_map[node] = color_idx

    return color_map


def build_display_array(
    domain_slice: np.ndarray,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None,
) -> tuple[np.ndarray, bool, bool]:
    """
    Combine domain slice and land/sea/boundary/excluded mask into a single
    display index array:
      -3: Excluded points
      -2: Boundary points
      -1: Land points
      0..num_colors-1: Domain colors
    """
    ny, nx = domain_slice.shape
    disp = np.full((ny, nx), VAL_LAND, dtype=np.int32)

    has_boundary = False
    has_excluded = False

    # First apply grid mask features if available
    if grid_mask is not None and grid_mask.shape == (ny, nx):
        disp[grid_mask == 0] = VAL_LAND
        if np.any(grid_mask == 2):
            disp[grid_mask == 2] = VAL_BOUNDARY
            has_boundary = True
        if np.any(grid_mask == 3):
            disp[grid_mask == 3] = VAL_EXCLUDED
            has_excluded = True

    # Then overlay domain IDs
    for p, c_idx in color_map.items():
        disp[domain_slice == p] = c_idx

    return disp, has_boundary, has_excluded


def get_feature_colormap(num_domain_colors: int):
    """
    Create colormap and normalization for:
      -3: Excluded points (light gray #d0d0d0)
      -2: Boundary points (magenta #ff00ff)
      -1: Land points (dark green #006400)
      0..num_domain_colors-1: Distinct domain colors
    """
    num_domain_colors = max(num_domain_colors, 1)

    c_excluded = "#d0d0d0"  # light gray
    c_boundary = "#ff00ff"  # magenta
    c_land = "#006400"  # dark green

    color_list = [c_excluded, c_boundary, c_land]
    for i in range(num_domain_colors):
        color_list.append(DISTINCT_DOMAIN_PALETTE[i % len(DISTINCT_DOMAIN_PALETTE)])

    cmap = colors.ListedColormap(color_list)
    bounds = np.arange(-3.5, num_domain_colors + 0.5, 1.0)
    norm = colors.BoundaryNorm(bounds, cmap.N)
    return cmap, norm


def annotate_domains(
    ax: plt.Axes,
    domain_slice: np.ndarray,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None = None,
    is_global: bool = False,
):
    """
    Annotate each domain with its base-0 domain number and active sea point count (size)
    in the center of the domain.
    """
    ny, nx = domain_slice.shape
    unique_domains = sorted([int(p) for p in np.unique(domain_slice) if p > 0])

    for domain_id in unique_domains:
        # Identify active points in this domain (excluding non-active points if mask available)
        mask = domain_slice == domain_id
        if grid_mask is not None and grid_mask.shape == (ny, nx):
            mask = mask & (grid_mask > 0) & (grid_mask != 3)

        size = int(np.sum(mask))
        if size == 0:
            continue

        y_coords, x_coords = np.where(mask)
        # Center in grid coordinate box system:
        # Cell (y, x) spans x in [x, x+1] and y in [y, y+1], center is (x + 0.5, y + 0.5)
        cy = float(np.mean(y_coords)) + 0.5

        if is_global and nx > 1:
            # For longitudinal wrapping grids, compute circular mean for x
            angles = 2.0 * np.pi * (x_coords.astype(float) + 0.5) / nx
            mean_sin = np.mean(np.sin(angles))
            mean_cos = np.mean(np.cos(angles))
            mean_angle = np.arctan2(mean_sin, mean_cos)
            if mean_angle < 0:
                mean_angle += 2.0 * np.pi
            cx = (mean_angle / (2.0 * np.pi)) * nx
        else:
            cx = float(np.mean(x_coords)) + 0.5

        # Base 0 domain number
        domain_num_base0 = domain_id - 1 if domain_id >= 1 else domain_id
        text_str = f"D{domain_num_base0}\n({size})"

        txt = ax.text(
            cx,
            cy,
            text_str,
            color="white",
            fontsize=8,
            fontweight="bold",
            ha="center",
            va="center",
            linespacing=0.9,
            zorder=5,
        )
        txt.set_path_effects(
            [
                path_effects.Stroke(linewidth=2.5, foreground="black"),
                path_effects.Normal(),
            ]
        )


def setup_plot_axes(
    ax: plt.Axes,
    disp_data: np.ndarray,
    cmap: colors.Colormap,
    norm: colors.Normalize,
    title: str,
    domain_slice: np.ndarray,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None,
    is_global: bool,
    has_boundary: bool,
    has_excluded: bool,
):
    """
    Render map slice on Cartesian grid using box-fill representation (pcolormesh)
    with equal aspect ratio and domain center annotations.
    """
    ny, nx = disp_data.shape
    ax.set_aspect("equal", adjustable="box")

    # Box-fill rendering: pcolormesh accurately draws pixel grid boxes on Cartesian coordinates
    x_edges = np.arange(nx + 1)
    y_edges = np.arange(ny + 1)
    ax.pcolormesh(
        x_edges,
        y_edges,
        disp_data,
        cmap=cmap,
        norm=norm,
        edgecolors="none",
        shading="flat",
    )

    ax.set_xlim(0, nx)
    ax.set_ylim(0, ny)
    ax.set_xlabel("X (Grid columns)")
    ax.set_ylabel("Y (Grid rows)")
    ax.set_title(title, fontsize=11, fontweight="bold")

    # Plot domain number (base 0) and size in domain centers
    annotate_domains(
        ax,
        domain_slice,
        color_map,
        grid_mask=grid_mask,
        is_global=is_global,
    )

    _ = (has_boundary, has_excluded)


def sample_indices(total_maps: int, step: int) -> list[int]:
    """
    Select map indices according to step/stride, always ensuring the first (0)
    and last (total_maps - 1) iterations are included.
    """
    if total_maps <= 1:
        return [0]

    step = max(1, step)
    selected = list(range(0, total_maps, step))
    if (total_maps - 1) not in selected:
        selected.append(total_maps - 1)
    return sorted(set(selected))


def plot_single_map(
    map_data: np.ndarray,
    map_idx: int,
    total_maps: int,
    num_domains: int,
    title_prefix: str,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None,
    is_global: bool = False,
    output_path: Path | None = None,
):
    """
    Plot the full domain map array on a Cartesian grid with equal aspect ratio.
    """
    disp, has_boundary, has_excluded = build_display_array(
        map_data, color_map, grid_mask
    )
    num_p_colors = max(color_map.values()) + 1 if color_map else 1
    cmap, norm = get_feature_colormap(num_p_colors)

    fig, ax = plt.subplots(figsize=(9, 6))

    step_str = f" [Step {map_idx + 1}/{total_maps}]" if total_maps > 1 else ""
    title = f"{title_prefix}{step_str}\nDomains: {num_domains}"

    setup_plot_axes(
        ax,
        disp,
        cmap,
        norm,
        title,
        map_data,
        color_map,
        grid_mask,
        is_global,
        has_boundary,
        has_excluded,
    )

    plt.tight_layout()

    if output_path is not None:
        plt.savefig(str(output_path), dpi=150, bbox_inches="tight")
        plt.close(fig)
        print(f"Saved plot to: {output_path}")
    else:
        plt.show()


def create_animation(
    maps: np.ndarray,
    indices: list[int],
    num_domains: int,
    title_prefix: str,
    color_map: dict[int, int],
    grid_mask: np.ndarray | None,
    output_path: Path,
    is_global: bool = False,
    fps: int = 2,
):
    """
    Generate an animated GIF across sampled map iterations.
    """
    import io

    from PIL import Image

    total_maps = maps.shape[0]
    num_p_colors = max(color_map.values()) + 1 if color_map else 1
    cmap, norm = get_feature_colormap(num_p_colors)

    pil_frames: list[Image.Image] = []
    for idx in indices:
        disp, has_boundary, has_excluded = build_display_array(
            maps[idx], color_map, grid_mask
        )

        fig, ax = plt.subplots(figsize=(9, 6), facecolor="white")
        title = f"{title_prefix} [Step {idx + 1}/{total_maps}]\nDomains: {num_domains}"

        setup_plot_axes(
            ax,
            disp,
            cmap,
            norm,
            title,
            maps[idx],
            color_map,
            grid_mask,
            is_global,
            has_boundary,
            has_excluded,
        )

        plt.tight_layout()

        buf = io.BytesIO()
        plt.savefig(
            buf,
            format="png",
            dpi=120,
            facecolor="white",
            edgecolor="none",
        )
        plt.close(fig)
        buf.seek(0)
        frame_img = Image.open(buf).convert("RGB")
        pil_frames.append(frame_img)

    duration_ms = int(1000.0 / max(1, fps))
    # Save animated GIF using PIL with disposal=2 (restore to background) to prevent black background / ghosting
    pil_frames[0].save(
        str(output_path),
        save_all=True,
        append_images=pil_frames[1:],
        duration=duration_ms,
        loop=0,
        disposal=2,
    )
    print(
        f"Saved animation ({len(pil_frames)} frames from {total_maps} total maps) to: {output_path}"
    )


def main():
    """
    Main entry point for plot_UQ_domains.
    """
    parser = argparse.ArgumentParser(
        description="Plot WAVEWATCH IV UQ grid domain maps from NetCDF file."
    )
    parser.add_argument(
        "domain_file",
        type=str,
        nargs="?",
        default=None,
        help="Path to the NetCDF domain file.",
    )
    parser.add_argument(
        "--input",
        "-i",
        type=str,
        default=None,
        dest="input_file",
        help="Path to the NetCDF domain file (alternative to positional argument).",
    )
    parser.add_argument(
        "--type",
        "-t",
        type=str,
        default="png",
        help="Output graphic format (e.g. png, jpg, jpeg, pdf, eps, gif). Default: png.",
    )
    parser.add_argument(
        "--animate",
        action="store_true",
        help="Generate animated GIF across map iterations.",
    )
    parser.add_argument(
        "--step",
        "-n",
        type=int,
        default=1,
        help="Sample every n-th iteration / map in animations (default: 1). Initial and final maps are always included.",
    )
    parser.add_argument(
        "--fps",
        type=int,
        default=2,
        help="Frames per second for animation (default: 2).",
    )

    args = parser.parse_args()

    target_file = args.input_file or args.domain_file
    if not target_file:
        parser.error(
            "NetCDF domain file path must be provided as a positional argument or via --input / -i."
        )

    input_path = Path(target_file)

    try:
        maps, num_domains, grid_title, grid_mask, is_global = read_domain_file(
            input_path
        )
    except (OSError, KeyError, ValueError) as e:
        print(f"Error reading domain file: {e}")
        sys.exit(1)

    total_maps = maps.shape[0]
    if num_domains <= 0:
        num_domains = int(np.max(maps))

    # Clean and determine output file extension
    out_ext = args.type.strip().lower().lstrip(".")
    if not out_ext:
        out_ext = "png"

    # Derive output filename from input file name, replacing .nc with graphic extension
    input_filename = input_path.name
    if input_filename.endswith(".nc"):
        base_name = input_filename[:-3]
    else:
        base_name = input_path.stem
    output_filename = f"{base_name}.{out_ext}"

    # Always produce output in the current working directory where the tool is executed
    output_path = Path.cwd() / output_filename

    # Up to 10 colors, but no more than the number of domains
    max_colors = min(10, max(1, num_domains))

    # Animate if requested or if output format is gif
    is_gif = out_ext == "gif"
    if args.animate or is_gif:
        if total_maps < 2:
            print(
                "Notice: File contains only 1 domain map. Generating single image/gif frame."
            )
        if not output_filename.endswith(".gif"):
            output_path = Path.cwd() / f"{base_name}.gif"

        indices = sample_indices(total_maps, args.step)
        # Build adjacency graph and minimal graph coloring across sampled animation frames
        adj = build_domain_adjacency_graph(maps[indices], is_global=is_global)
        color_map = compute_minimal_domain_coloring(adj, max_colors=max_colors)

        create_animation(
            maps,
            indices,
            num_domains,
            grid_title,
            color_map,
            grid_mask,
            output_path,
            is_global=is_global,
            fps=args.fps,
        )
    else:
        # Plot the entire map array for the final map iteration
        last_idx = total_maps - 1
        # Build adjacency graph and minimal coloring strictly for the final map being displayed
        adj = build_domain_adjacency_graph(
            maps[last_idx : last_idx + 1], is_global=is_global
        )
        color_map = compute_minimal_domain_coloring(adj, max_colors=max_colors)

        plot_single_map(
            maps[last_idx],
            last_idx,
            total_maps,
            num_domains,
            grid_title,
            color_map,
            grid_mask,
            is_global=is_global,
            output_path=output_path,
        )


if __name__ == "__main__":
    main()
